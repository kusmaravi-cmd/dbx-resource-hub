"""Executive summary in Markdown, generated from an evaluated assessment."""

from .framework import LEVER_INDEX, model


def _f(x):
    return "n/a" if x is None else f"{x:.1f}"


def markdown_report(doc, res, meta=None):
    t = res["tiers"]
    L = []
    L.append(f"# DataPulse assessment: {doc.get('name') or 'Untitled'}")
    L.append("")
    L.append(f"**Organisation:** {doc.get('org') or 'n/a'}  ")
    L.append(f"**Mode:** {doc.get('mode')} ({model.ASSESSMENT_MODES.get(doc.get('mode'), '')})  ")
    L.append(f"**Target level:** {doc.get('target_level')}  ")
    m = doc.get("meta") or {}
    if m.get("date"):
        L.append(f"**Date:** {m['date']}  ")
    if m.get("assessor"):
        L.append(f"**Assessor:** {m['assessor']}  ")
    L.append(f"**Framework:** v{res['framework_version']}, evaluated {res['evaluated_at']}")
    L.append("")
    L.append("## Headline")
    L.append("")
    ceil = t["T1"]["ceiling"]
    L.append(f"- **Readiness ceiling (A5): {_f(ceil)}**, bound by {', '.join(t['T1']['binding']) or 'n/a'}. "
             "No AI outcome can exceed this until the binding dimension improves.")
    if t["T1"]["ceiling_evidence_backed"] is not None and ceil is not None and t["T1"]["ceiling_evidence_backed"] < ceil:
        L.append(f"- Evidence-backed ceiling is {_f(t['T1']['ceiling_evidence_backed'])}: claims above this still need evidence.")
    L.append(f"- **AI for Data: {_f(t['T2']['score'])}**, flywheel {t['T2']['flywheel'] or 'n/a'}.")
    L.append(f"- **Execution: {_f(t['T3']['score'])}**" + (f", critical: {', '.join(t['T3']['critical'])}" if t["T3"]["critical"] else "") + ".")
    if res["inflation"]:
        L.append(f"- Claimed scores were reduced by enforcement on: {', '.join(res['inflation'])}.")
    c = res["counts"]
    L.append(f"- Findings: {c['blocker']} blockers, {c['cap']} caps, {c['warning']} warnings.")
    L.append("")
    L.append("## Velocity")
    L.append("")
    L.append("| Dimension | Level | Source |")
    L.append("|---|---|---|")
    for v in model.VELOCITY:
        x = res["velocity"][v["id"]]
        L.append(f"| {v['id']} | {_f(x['level'])} | {x['source'] or 'not assessed'} |")
    L.append("")
    L.append("## Dimensions: claimed vs enforced")
    L.append("")
    L.append("| Dim | Name | Claimed | Evidence-backed | Enforced | Why it was capped |")
    L.append("|---|---|---|---|---|---|")
    for d in model.DIMENSIONS:
        r = res["dimensions"][d["id"]]
        why = "; ".join(f"{c['rule']} {c['reason']}" for c in r["caps"]) or ""
        if r["provisional"]:
            why = ("provisional (coverage). " + why).strip()
        L.append(f"| {d['id']} | {d['name']} | {_f(r['claimed'])} | {_f(r['evidence_backed'])} | {_f(r['enforced'])} | {why} |")
    if res["use_cases"]:
        L.append("")
        L.append("## AI use-case readiness")
        L.append("")
        L.append("| Use case | Job | Readiness | Status | Why |")
        L.append("|---|---|---|---|---|")
        for u in res["use_cases"]:
            L.append(f"| {u.get('name')} | {u.get('job')} | {_f(u.get('readiness'))} | **{u['status']}** | {u.get('reason', '')} |")
    L.append("")
    L.append("## Roadmap of enforced levers")
    L.append("")
    for w in res["levers"]["waves"]:
        L.append(f"### {w['name']} ({w['window']}): {w['purpose']}")
        L.append("")
        for lid in w["levers"]:
            lv = LEVER_INDEX[lid]
            st = res["levers"]["plan"][lid]["status"]
            L.append(f"- **{lid} {lv['name']}** [{lv['mode']}, {lv['effort']}, ~{lv['ttv_days']}d, {st}]")
            L.append(f"  - Enforced by: {lv['enforcement']}")
            L.append(f"  - KPI: {lv['kpi']['name']} ({lv['kpi']['unit']}, {lv['kpi']['direction'].replace('_', ' ')})")
        for v in w["violations"]:
            L.append(f"- Warning ({v['rule']}): {v['message']}")
        L.append("")
    blockers = [f for f in res["findings"] if f["severity"] in ("blocker", "cap")]
    if blockers:
        L.append("## Blockers and caps")
        L.append("")
        for f in blockers:
            L.append(f"- **{f['rule']}** ({f['severity']}): {f['message']}")
        L.append("")
    L.append("---")
    L.append("Generated by DataPulse. Scores are enforced: claims need evidence, dimensions respect their dependencies, "
             "and levers count only once a system enforces them.")
    return "\n".join(L) + "\n"

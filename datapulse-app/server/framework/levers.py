"""DataPulse lever catalog.

A lever is an intervention that moves one or more dimensions. A lever counts
only when it is *enforced*: a system blocks, detects or corrects
non-compliance. Writing a standard is not enough (A3).

Fields
  targets         {dim: expected lift in levels once Enforced}
  preconditions   {dim: minimum enforced level before this lever can be Enforced}
  requires        levers that must be Enforced first (sequencing)
  pair_with       for directive levers: at least one of these must be Enforced too
  mode            preventive | detective | corrective | directive
  enforcement     the mechanism that makes it real, platform-agnostic
  evidence        what proves it is enforced (asked for at the Enforced transition)
  kpi             leading measure with direction; target is set per assessment
  impl            reference implementations: platform-agnostic first, then per platform
"""


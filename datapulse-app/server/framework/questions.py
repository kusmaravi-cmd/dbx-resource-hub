def Q(id, dim, weight, prompt, intent, levels, *, velocity=None, roles=None, jobs=None,
      probes=None, evidence=None, red_flags=None):
    assert len(levels) == 5, id
    return {
        "id": id, "kind": "attested", "dim": dim, "weight": weight, "velocity": velocity,
        "roles": roles or [], "jobs": jobs or [], "prompt": prompt, "intent": intent,
        "probes": probes or [], "levels": levels, "evidence": evidence or [],
        "red_flags": red_flags or [],
    }


def M(id, dim, prompt, intent, unit, direction, bands, *, velocity=None, roles=None,
      how_to_measure="", weight="High"):
    """Metric question. `bands` are the four thresholds between L1|L2|L3|L4|L5.

    lower_better: value > b[0] -> 1, > b[1] -> 2, > b[2] -> 3, > b[3] -> 4, else 5
    higher_better: value < b[0] -> 1, < b[1] -> 2, < b[2] -> 3, < b[3] -> 4, else 5
    """
    assert len(bands) == 4 and direction in ("lower_better", "higher_better"), id
    return {
        "id": id, "kind": "metric", "dim": dim, "weight": weight, "velocity": velocity,
        "roles": roles or [], "jobs": [], "prompt": prompt, "intent": intent,
        "unit": unit, "direction": direction, "bands": bands, "how_to_measure": how_to_measure,
    }



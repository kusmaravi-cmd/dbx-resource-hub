def metric_level(q, value):
    """Map a metric value to a 1-5 level using the question's bands."""
    if value is None or value == "":
        return None
    try:
        v = float(value)
    except (TypeError, ValueError):
        return None
    b = q["bands"]
    if q["direction"] == "lower_better":
        for i, t in enumerate(b):
            if v > t:
                return i + 1
        return 5
    for i, t in enumerate(b):
        if v < t:
            return i + 1
    return 5

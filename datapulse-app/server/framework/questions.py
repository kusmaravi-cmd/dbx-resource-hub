"""DataPulse question bank.

Design rules every question follows:
  * Episodic, not aspirational. Ask about the last real occurrence ("walk me
    through the last time...") rather than "do you have X?". Policies describe
    intent; episodes reveal operation.
  * Five behaviourally anchored levels. Each level is observable and mutually
    exclusive, so two assessors reach the same answer.
  * Every level of 3 or above names the evidence that would prove it.
  * Red flags list the answer patterns that usually signal inflation.
  * Measured metrics (kind="metric") triangulate attested answers. The engine
    caps a dimension that claims more than one level above what its metrics show.
  * Platform-agnostic wording. No product names in prompts or anchors.
"""

